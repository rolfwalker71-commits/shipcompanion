const saved = localStorage.getItem('cruise-locale')
const locale = saved === 'en' || saved === 'de' ? saved : navigator.language.startsWith('de') ? 'de' : 'en'

void i18n.use(initReactI18next).init({
  resources,
  lng: locale,
  fallbackLng: 'de',
  interpolation: { escapeValue: false },
})

function applyDocumentLang(lng: string): void {
  document.documentElement.lang = lng.startsWith('de') ? 'de-DE' : 'en-GB'
}

applyDocumentLang(i18n.language)
i18n.on('languageChanged', applyDocumentLang)

export default i18n
